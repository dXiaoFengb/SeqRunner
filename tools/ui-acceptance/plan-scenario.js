async page => {
  const check = (ok, message) => { if (!ok) throw new Error(message) }
  const wait = async () => { await page.waitForTimeout(500); await page.locator('.draft-state').waitFor({state:'hidden', timeout:15000}) }
  await page.getByRole('button',{name:'脚本',exact:true}).click()
  for (const name of ['验收软件甲','验收软件乙']) {
    await page.getByRole('button',{name:'新建脚本'}).click()
    await wait()
    await page.getByRole('textbox',{name:'软件名称'}).fill(name)
    await page.getByRole('textbox',{name:'软件名称'}).press('Tab')
    await wait()
    await page.getByRole('button',{name:'← 返回',exact:true}).click()
  }
  await page.getByRole('button',{name:'计划',exact:true}).click()
  check(await page.getByText('暂无计划').isVisible(),'空计划状态未显示')
  await page.getByRole('button',{name:'新建计划'}).click()
  await page.getByRole('button',{name:'重命名计划'}).click()
  await page.getByRole('textbox',{name:'计划名称'}).fill('验收计划甲')
  await page.getByRole('textbox',{name:'计划名称'}).press('Enter')
  await wait()
  await page.getByRole('button',{name:'添加定时'}).click(); await wait()
  await page.getByRole('button',{name:'添加定时'}).click()
  await page.getByText('保存失败，草稿将保留',{exact:false}).waitFor({timeout:15000})
  const slots = page.locator('.queue-table:not(.task-table) .queue-table-row')
  await slots.nth(1).getByRole('combobox',{name:'小时'}).click()
  const menu = page.getByRole('listbox',{name:'小时'})
  const before = await menu.evaluate(el=>el.scrollTop), box = await menu.boundingBox()
  if (!box) throw new Error('小时列表不可见')
  await page.mouse.move(box.x+10,box.y+box.height-3); await page.waitForTimeout(600)
  check(await menu.evaluate(el=>el.scrollTop) === before,'小时列表悬停自动滚动')
  await menu.getByRole('option',{name:'10 时'}).click(); await wait()
  check(await page.getByText('保存失败，草稿将保留',{exact:false}).count()===0,'冲突修正后旧错误仍显示')
  await slots.nth(1).getByRole('combobox',{name:'分钟'}).click()
  const minutes = page.getByRole('listbox',{name:'分钟'}), mb = await minutes.boundingBox(), ms = await minutes.evaluate(el=>el.scrollTop)
  if (!mb) throw new Error('分钟列表不可见')
  await page.mouse.move(mb.x+10,mb.y+mb.height-3); await page.waitForTimeout(600)
  check(await minutes.evaluate(el=>el.scrollTop) === ms,'分钟列表悬停自动滚动')
  await page.keyboard.press('Escape')
  await slots.nth(0).locator('.drag-order').dragTo(slots.nth(1))
  check((await slots.nth(0).getByRole('combobox',{name:'小时'}).innerText()).includes('10'),'定时拖拽未排序')
  await wait()
  for (const day of ['一','二','三','四','五','六']) await slots.nth(0).locator(`.weekday-tag[aria-label="移除周${day}"]`).click()
  await slots.nth(0).locator('.weekday-tag[aria-label="移除周日"]').click()
  check(await page.getByText('请至少选择一个运行日。').isVisible(), '最后一个运行日未被保护')
  await wait()
  for (const name of ['验收软件甲','验收软件乙']) {
    await page.getByRole('button',{name:'添加任务'}).click()
    await page.getByRole('combobox',{name:'选择软件脚本'}).selectOption({label:name})
    await wait()
  }
  const tasks = page.locator('.task-table .task-row')
  await tasks.nth(0).locator('.drag-order').dragTo(tasks.nth(1))
  check((await tasks.nth(0).innerText()).includes('验收软件乙'),'任务拖拽未排序')
  await wait(); await page.getByRole('button',{name:'返回计划列表'}).click()
  await page.getByRole('button',{name:'新建计划'}).click()
  await page.getByRole('button',{name:'重命名计划'}).click()
  await page.getByRole('textbox',{name:'计划名称'}).fill('验收计划乙')
  await page.getByRole('textbox',{name:'计划名称'}).press('Enter')
  await wait(); await page.getByRole('button',{name:'返回计划列表'}).click()
  const cards = page.locator('.plan-card')
  await cards.nth(0).locator('.plan-card-handle').dragTo(cards.nth(1))
  check((await cards.nth(0).innerText()).includes('验收计划乙'),'计划拖拽未排序')
  await wait()
  for (const width of [1080, 960, 640]) {
    await page.setViewportSize({width, height:800})
    await page.waitForTimeout(200)
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > document.documentElement.clientWidth)
    check(!overflow, `${width}px 页面发生横向溢出`)
    await page.screenshot({path:`viewport-${width}.png`})
  }
  await page.setViewportSize({width:1280,height:820})
  await page.reload(); await page.getByRole('button',{name:'计划',exact:true}).click()
  await page.locator('.plan-card').first().waitFor({timeout:15000})
  check((await page.locator('.plan-card').first().innerText()).includes('验收计划乙'), '计划顺序重载后未保存')
  return 'PASS: 空状态、计划/定时/任务拖拽、小时/分钟悬停、冲突修正与保存'
}
